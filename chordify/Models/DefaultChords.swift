import SwiftData

/// アプリ初回起動時にコードブックへシードするデフォルトコード定義
enum DefaultChords {
    /// UserDefaults のシードフラグキー（更新したら末尾の番号を上げる）
    static let seedKey = "defaultChordsSeeded_v2"

    static func seed(into context: ModelContext) {
        // (コード名, フォルダ, [E弦, A弦, D弦, G弦, B弦, e弦])
        // fret: -1=ミュート  0=開放  1+=絶対フレット番号
        let entries: [(String, String, [Int])] = [
            // ── メジャー ──────────────────────────────────────────
            ("C", "メジャー", [-1, 3, 2, 0, 1, 0]),
            ("D", "メジャー", [-1, -1, 0, 2, 3, 2]),
            ("E", "メジャー", [0, 2, 2, 1, 0, 0]),
            ("F", "メジャー", [1, 3, 3, 2, 1, 1]),
            ("G", "メジャー", [3, 2, 0, 0, 0, 3]),
            ("A", "メジャー", [-1, 0, 2, 2, 2, 0]),
            ("B", "メジャー", [-1, 2, 4, 4, 4, 2]),
            // ── マイナー ──────────────────────────────────────────
            ("Am", "マイナー", [-1, 0, 2, 2, 1, 0]),
            ("Bm", "マイナー", [-1, 2, 4, 4, 3, 2]),
            ("Dm", "マイナー", [-1, -1, 0, 2, 3, 1]),
            ("Em", "マイナー", [0, 2, 2, 0, 0, 0]),
            // ── ドミナント 7th ────────────────────────────────────
            ("A7", "7th", [-1, 0, 2, 0, 2, 0]),
            ("B7", "7th", [-1, 2, 1, 2, 0, 2]),
            ("C7", "7th", [-1, 3, 2, 3, 1, 0]),
            ("D7", "7th", [-1, -1, 0, 2, 1, 2]),
            ("E7", "7th", [0, 2, 0, 1, 0, 0]),
            ("G7", "7th", [3, 2, 0, 0, 0, 1]),
            // ── メジャー 7th ──────────────────────────────────────
            ("Cmaj7", "メジャー7th", [-1, 3, 2, 0, 0, 0]),
            ("Dmaj7", "メジャー7th", [-1, -1, 0, 2, 2, 2]),
            ("Amaj7", "メジャー7th", [-1, 0, 2, 1, 2, 0]),
            // ── マイナー 7th ──────────────────────────────────────
            ("Am7", "マイナー7th", [-1, 0, 2, 0, 1, 0]),
            ("Dm7", "マイナー7th", [-1, -1, 0, 2, 1, 1]),
            ("Em7", "マイナー7th", [0, 2, 2, 0, 3, 0]),
        ]

        for (name, folder, frets) in entries {
            let strings = frets.map { StringFingering(fret: $0) }
            let chord = ChordDiagram(
                name: name,
                fingering: ChordFingering(strings: strings, startFret: 1),
                isGlobal: true,
                folder: folder
            )
            context.insert(chord)
        }
    }
}
